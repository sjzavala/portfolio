/**
 * Turns Playwright's JSON reporter output into lab/results.js, which the
 * QA Lab section on the homepage renders. Run after `playwright test`:
 *
 *   node scripts/lab-results.mjs [path/to/results.json]
 *
 * Grouping: one group per spec file, named after the file's top-level
 * describe block (falling back to the file name).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const input = resolve(process.argv[2] ?? 'test-results/results.json');
const output = resolve('lab/results.js');

const report = JSON.parse(readFileSync(input, 'utf8'));

const projects = (report.config?.projects ?? []).map((p) => p.name);
const groups = new Map();
const totals = { tests: 0, passed: 0, failed: 0, skipped: 0, flaky: 0, durationMs: 0 };

function walk(suite, file, titlePath) {
  const path = suite.title && suite.title !== file ? [...titlePath, suite.title] : titlePath;

  for (const spec of suite.specs ?? []) {
    for (const test of spec.tests ?? []) {
      const last = test.results[test.results.length - 1] ?? {};
      // Playwright's outcome: expected | unexpected | flaky | skipped
      const status =
        test.status === 'expected' ? 'passed'
        : test.status === 'flaky' ? 'flaky'
        : test.status === 'skipped' ? 'skipped'
        : 'failed';

      totals.tests += 1;
      if (status === 'passed') totals.passed += 1;
      else if (status === 'flaky') { totals.flaky += 1; totals.passed += 1; }
      else if (status === 'skipped') totals.skipped += 1;
      else totals.failed += 1;

      const groupName = path[0] ?? file.replace(/\.spec\.[jt]s$/, '');
      if (!groups.has(file)) groups.set(file, { name: groupName, file, tests: [] });
      groups.get(file).tests.push({
        title: [...path.slice(1), spec.title].join(' › '),
        project: test.projectName,
        status,
        duration: last.duration ?? 0,
      });
    }
  }
  for (const child of suite.suites ?? []) walk(child, file, path);
}

for (const fileSuite of report.suites ?? []) {
  walk(fileSuite, fileSuite.file ?? fileSuite.title, []);
}

totals.durationMs = Math.round(report.stats?.duration ?? 0);

// Show groups in reading order rather than alphabetical file order.
const ORDER = ['homepage', 'navigation', 'links', 'qa-lab', 'responsive', 'accessibility'];
const rank = (g) => {
  const i = ORDER.findIndex((name) => g.file.includes(name));
  return i === -1 ? ORDER.length : i;
};

const data = {
  generatedAt: report.stats?.startTime ?? new Date().toISOString(),
  projects,
  groups: [...groups.values()].sort((a, b) => rank(a) - rank(b)),
  totals,
};

writeFileSync(
  output,
  `/* Generated by scripts/lab-results.mjs from ${input.replace(process.cwd() + '/', '')}. Do not edit by hand. */\n` +
  `window.LAB_RESULTS = ${JSON.stringify(data, null, 2)};\n`,
);

console.log(
  `lab/results.js written: ${totals.tests} tests, ${totals.passed} passed, ` +
  `${totals.failed} failed, ${totals.skipped} skipped across ${projects.length} projects.`,
);
if (totals.failed) process.exitCode = 1;
